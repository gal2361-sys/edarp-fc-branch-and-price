"""Objective grid for exact lower-bound rounding. See docs/GRID_ROUNDING.md.

For instances with integer travel times, service time, earliest pickups, loads and
battery data and beta_c = 1, some optimal solution has every time and charge in
(1/2)Z (in Z when every deadline d_i is an integer), so the optimal objective lies in
the lattice generated by ALPHA1 and ALPHA2 * h, h = 1/2 or 1. A valid lower bound can
then be rounded up to that lattice. Returns None when the conditions do not hold.
"""

from __future__ import annotations

import math
from fractions import Fraction

from edarp import ALPHA1, ALPHA2, Instance

ROUND_EPS = 1e-5     # a bound is first lowered by this before rounding up (float noise)


def _is_int(x) -> bool:
    return float(x) == int(x)


def _frac(x: float) -> Fraction:
    return Fraction(str(x)).limit_denominator(10**6)


def _gcd(a: Fraction, b: Fraction) -> Fraction:
    den = a.denominator * b.denominator // math.gcd(a.denominator, b.denominator)
    return Fraction(math.gcd(int(a * den), int(b * den)), den)


def grid_step(inst: Instance) -> float | None:
    data = list(inst.t) + [inst.sigma, inst.beta_d, inst.beta_m] + list(inst.a) + list(inst.q)
    if inst.beta_c != 1 or not all(_is_int(v) for v in data):
        return None
    if all(_is_int(d) for d in inst.d):
        h = Fraction(1)
    elif all(_is_int(2 * d) for d in inst.d):
        h = Fraction(1, 2)
    else:
        return None
    return float(_gcd(_frac(ALPHA1), _frac(ALPHA2) * h))


def round_up(lb: float, step: float | None) -> float:
    """Smallest lattice point >= lb - ROUND_EPS (identity without a step)."""
    if step is None or not math.isfinite(lb):
        return lb
    return math.ceil((lb - ROUND_EPS) / step) * step
